-- Вид адресов сайта и сжатие — в задаче аудита, а не в памяти функции.
--
-- 1. Вид адресов (протокол и «www») обработчик аудита держал в переменной
--    модуля. Один воркер ведёт несколько запросов сразу: аудит второго сайта
--    переключал её, и у первого все ссылки становились «чужими» — обход молча
--    заканчивался на главной. Кроме того, вид брался из введённого адреса, а не
--    из того, где сайт открылся после переадресаций: введённый «www.site.ru»
--    у сайта без www давал переадресацию на каждой странице и штраф в оценке.
--    Теперь вид определяется при запуске по стартовой странице и хранится
--    здесь; каждая следующая пачка обхода берёт его отсюда.
--
-- 2. Сжатие проверялось по первой попавшейся странице пачки и запоминалось на
--    весь сайт в памяти функции — годился и ответ XML-карты, и отказ защиты от
--    ботов, отчего в смету попадало ложное «сжатия нет». Теперь проверка одна
--    на задачу, по стартовой странице; NULL — «проверить не удалось».

ALTER TABLE public.audit_tasks
  ADD COLUMN IF NOT EXISTS site_origin text,
  ADD COLUMN IF NOT EXISTS site_is_compressed boolean,
  ADD COLUMN IF NOT EXISTS site_compression_type text;

COMMENT ON COLUMN public.audit_tasks.site_origin IS
  'Протокол и хост сайта после переадресаций стартовой страницы, например https://www.site.ru';
COMMENT ON COLUMN public.audit_tasks.site_is_compressed IS
  'Сжатие ответа стартовой HTML-страницы; NULL — проверить не удалось';
COMMENT ON COLUMN public.audit_tasks.site_compression_type IS
  'Способ сжатия (gzip, br, deflate) или NULL';

