import React, { useEffect } from 'react';
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card';
import { Info } from 'lucide-react';
import PageSeo from '@/components/seo/PageSeo';

/**
 * Хостинги клиентов.
 *
 * Раздел был опасной бутафорией. Форма принимала адрес сервера, логин, пароль и
 * ключ доступа к хостингу клиента и складывала всё это в localStorage браузера
 * открытым текстом — то есть пароли от чужих серверов лежали в браузере и были
 * доступны любому скрипту на странице (а сторонний скрипт на сайте тогда был).
 * Кнопка «Проверить подключение» никуда не подключалась: она сразу отвечала
 * «Подключение установлено успешно», что бы ни ввели.
 *
 * Заливать на хостинг пока нечего: сборка исправленной копии сайта не
 * реализована. Раздел оставлен пустым намеренно, чтобы никто не вводил сюда
 * настоящие доступы.
 */

/** Ключ, под которым старая версия раздела хранила доступы к хостингам. */
const LEGACY_HOSTINGS_KEY = 'admin_saved_hostings';

const HostingPage: React.FC = () => {
  // Новая страница ничего не пишет, но у тех, кто вводил доступы в старой
  // версии, пароли так и остались в браузере открытым текстом. Стираем их при
  // первом же заходе. Хранилище может быть недоступно (приватный режим,
  // запрет сайта) — тогда стирать нечего, ошибку глушим.
  useEffect(() => {
    try {
      window.localStorage.removeItem(LEGACY_HOSTINGS_KEY);
    } catch {
      /* хранилище недоступно — в нём и нечего удалять */
    }
  }, []);

  return (
    <div className="container mx-auto px-6 py-10 max-w-3xl">
      <PageSeo
        title="Хостинги клиентов: раздел пока не подключён"
        description="Подключение хостингов и выгрузка файлов на серверы клиентов пока не реализованы: оптимизация переписывает тексты страниц, а не собирает копию сайта."
        noindex
      />

      <Card>
        <CardHeader>
          <CardTitle className="flex items-center gap-2">
            <Info className="h-5 w-5 text-muted-foreground" />
            Раздел пока не подключён
          </CardTitle>
          <CardDescription>
            Выгрузки файлов на хостинг клиента в сервисе нет.
          </CardDescription>
        </CardHeader>
        <CardContent className="space-y-3 text-sm text-muted-foreground">
          <p>
            Оптимизация переписывает тексты и мета-теги страниц, а собранной копии сайта,
            которую можно было бы залить на сервер, она не создаёт.
          </p>
          <p>
            Когда выгрузка появится, доступы к хостингу будут храниться в секретах проекта на
            сервере. Вводить логины и пароли от чужих серверов в браузере нельзя — раньше они
            сохранялись прямо в нём открытым текстом.
          </p>
        </CardContent>
      </Card>
    </div>
  );
};

export default HostingPage;
