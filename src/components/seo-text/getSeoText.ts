function topicFor(pathname: string): string {
  const path = pathname.replace(/\/+$/, '') || '/';
  if (TOPICS[path]) return TOPICS[path];
  // Производное название из последнего сегмента
  const seg = path.split('/').filter(Boolean).pop() || '';
  const human = decodeURIComponent(seg).replace(/[-_]/g, ' ').trim();
  return human ? human.charAt(0).toUpperCase() + human.slice(1) : 'SEO-продвижение сайта';
}

